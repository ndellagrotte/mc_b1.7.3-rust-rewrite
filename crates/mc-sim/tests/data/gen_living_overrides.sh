#!/usr/bin/env sh
# Regenerates living_overrides.txt next to this script: the override set of
# the methods EntityLiving.java and EntityCreature.java declare beyond
# Entity.java's, in the vanilla b1.7.3 client (PLAN_v4 D2), which
# crates/mc-sim/tests/living_dispatch_coverage.rs checks the EntityLiving-level
# entity dispatch (crates/mc-sim/src/entity/dispatch.rs, WP-2.2) against.
# The EntityLiving counterpart of gen_entity_overrides.sh (same parsing
# rules; Entity.java's own methods are that script's).
#
#   sh crates/mc-sim/tests/data/gen_living_overrides.sh
#
# Classes: every class of the tree whose superclass chain reaches
# EntityLiving, except EntityClientPlayerMP / EntityOtherPlayerMP
# (multiplayer, D3).
#
# Rows (see the header the script writes):
#   method <Class> <name> <Class.java line> <parameter types, comma-separated>
#       every non-static, non-final, non-private method EntityLiving.java or
#       EntityCreature.java declares that Entity.java does not (constructors
#       excluded)
#   extends <Class> <Parent>
#       every in-scope EntityLiving subclass, with its direct superclass
#   override <Class> <method> <Class.java line>
#       a method an in-scope class declares with the name and parameter types
#       of a `method` row of one of its ancestors
#
# Output is sorted (C locale), so a rerun on the frozen tree is byte-identical.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../../.." && pwd)
SRC="$ROOT/.reference/mc_b1.7.3_release/1.7.3-LTS/src/minecraft/net/minecraft/src"
OUT="$HERE/living_overrides.txt"
[ -f "$SRC/EntityLiving.java" ] || { echo "gen_living_overrides: no vanilla tree at $SRC" >&2; exit 1; }
export LC_ALL=C
cd "$SRC"

# "Class Parent" for every class declaration with an extends clause.
pairs=$(grep -h -E '^public (abstract |final )*class [A-Za-z0-9_]+ extends [A-Za-z0-9_]+' ./*.java \
    | sed -E 's/^public (abstract |final )*class ([A-Za-z0-9_]+) extends ([A-Za-z0-9_]+).*/\2 \3/')

# The in-scope subclasses of EntityLiving, to a fixed point.
set_=" EntityLiving "
changed=1
while [ "$changed" = 1 ]; do
    changed=0
    for row in $(printf '%s\n' "$pairs" | tr ' ' ':'); do
        c=${row%%:*}; p=${row#*:}
        case "$c" in EntityClientPlayerMP|EntityOtherPlayerMP) continue ;; esac
        case "$set_" in *" $p "*) ;; *) continue ;; esac
        case "$set_" in *" $c "*) continue ;; esac
        set_="$set_$c "
        changed=1
    done
done
classes=$(printf '%s\n' $set_ | grep -v '^EntityLiving$' | grep -v '^EntityCreature$' | sort)

body=$(awk '
function sig(line,    head, params, n, i, p, parts, m, out) {
    # Returns "name|types" for a method declaration line, or "" otherwise.
    if (line !~ /^    [A-Za-z]/) return ""
    if (line !~ /\) *(\{|throws|;)/) return ""
    head = line; sub(/\(.*/, "", head)
    if (head ~ /=/) return ""            # a field initialiser with a call
    params = line; sub(/^[^(]*\(/, "", params); sub(/\).*/, "", params)
    n = split(head, parts, " ")
    name = parts[n]
    MODS = " " head " "
    if (n < 2) return ""
    if (name == CLASS) return ""          # constructor
    if (parts[n-1] == "new" || parts[n-1] == "return" || parts[n-1] == "else") return ""
    out = ""
    m = split(params, p, ",")
    for (i = 1; i <= m; i++) {
        gsub(/^ +| +$/, "", p[i])
        if (p[i] == "") continue
        sub(/ +[A-Za-z_0-9]+$/, "", p[i])  # drop the parameter name
        out = out (out == "" ? "" : ",") p[i]
    }
    return name "|" out
}
FNR == 1 { CLASS = FILENAME; sub(/\.java$/, "", CLASS) }
FILENAME != "Entity.java" && FILENAME != "EntityLiving.java" && FNR < 20 && /^public (abstract |final )*class [A-Za-z0-9_]+ extends [A-Za-z0-9_]+/ {
    match($0, /class [A-Za-z0-9_]+ extends [A-Za-z0-9_]+/)
    split(substr($0, RSTART, RLENGTH), w, " ")
    print "extends " w[2] " " w[4]
}
{
    s = sig($0)
    if (s == "") next
    split(s, a, "|")
    if (FILENAME == "Entity.java") {
        entity[s] = 1
    } else if ((s in base) && MODS !~ / static /) {
        print "override " CLASS " " a[1] " " FNR
    } else if ((FILENAME == "EntityLiving.java" || FILENAME == "EntityCreature.java") && !(s in entity)) {
        if (MODS ~ / static / || MODS ~ / final / || MODS ~ / private /) next
        base[s] = 1
        print "method " CLASS " " a[1] " " FNR (a[2] == "" ? "" : " " a[2])
    }
}
' Entity.java EntityLiving.java EntityCreature.java $(for c in $classes; do printf '%s.java ' "$c"; done) | sort)

{
    echo "# EntityLiving.java / EntityCreature.java override set of the vanilla b1.7.3 client (PLAN_v4 D2),"
    echo "# generated by crates/mc-sim/tests/data/gen_living_overrides.sh from"
    echo "# .reference/mc_b1.7.3_release/1.7.3-LTS/src/minecraft/net/minecraft/src (the methods those two"
    echo "# declare beyond Entity.java's, and every in-scope EntityLiving subclass: not EntityClientPlayerMP,"
    echo "# EntityOtherPlayerMP). Do not edit: rerun the script. Read by"
    echo "# crates/mc-sim/tests/living_dispatch_coverage.rs."
    echo "#"
    echo "# method <Class> <name> <Class.java line> <parameter types>  non-static, non-final, non-private methods"
    echo "# extends <Class> <Parent>                                   every in-scope EntityLiving subclass"
    echo "# override <Class> <method> <Class.java line>                a subclass method with the signature of a method row"
    printf '%s\n' "$body"
} > "$OUT"
echo "gen_living_overrides: wrote $(grep -c '^override ' "$OUT") overrides, $(grep -c '^method ' "$OUT") methods, $(grep -c '^extends ' "$OUT") classes to $OUT"
