#!/usr/bin/env sh
# Regenerates item_overrides.txt next to this script: the override set of
# Item.java in the vanilla b1.7.3 client (PLAN_v4 D2), which
# crates/mc-sim/tests/item_dispatch_coverage.rs checks the item behaviour
# dispatch (crates/mc-sim/src/item/behaviour/mod.rs) against.
#
#   sh crates/mc-sim/tests/data/gen_item_overrides.sh
#
# Rows (see the header the script writes):
#   method <name> <Item.java line> <parameter types, comma-separated>
#       every non-static, non-final, non-private method Item.java declares
#       (constructors excluded)
#   extends <Class> <Parent>
#       every Item*.java class that extends another class, with its direct
#       superclass (ItemStack.java and ItemRenderer.java extend nothing and
#       are not Item subclasses; their methods are never override rows)
#   override <Class> <method> <Class.java line>
#       a method such a class declares with the name and parameter types of a
#       `method` row
#
# Parsing: as gen_block_overrides.sh (a method declaration is a line at the
# decompiler's 4-space class indent of the form
# `    [visibility] [modifiers] Type name(params) {`). Output is sorted (C
# locale), so a rerun on the frozen tree is byte-identical.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../../.." && pwd)
SRC="$ROOT/.reference/mc_b1.7.3_release/1.7.3-LTS/src/minecraft/net/minecraft/src"
OUT="$HERE/item_overrides.txt"
[ -f "$SRC/Item.java" ] || { echo "gen_item_overrides: no vanilla tree at $SRC" >&2; exit 1; }
export LC_ALL=C
cd "$SRC"

body=$(awk '
function sig(line,    head, params, n, i, p, parts, m, out) {
    # Returns "name|types" for a method declaration line, or "" otherwise.
    if (line !~ /^    [A-Za-z]/) return ""
    if (line !~ /\) *(\{|throws|;)/) return ""
    head = line; sub(/\(.*/, "", head)
    params = line; sub(/^[^(]*\(/, "", params); sub(/\).*/, "", params)
    n = split(head, parts, " ")
    # parts (whitespace split): [visibility] [modifiers] Type name
    name = parts[n]
    MODS = " " head " "
    if (n < 2) return ""                  # needs at least a type and a name
    if (name == CLASS) return ""          # constructor
    if (parts[n-1] == "new" || parts[n-1] == "return" || parts[n-1] == "else") return ""
    out = ""
    m = split(params, p, ",")
    for (i = 1; i <= m; i++) {
        gsub(/^ +| +$/, "", p[i])
        if (p[i] == "") continue
        sub(/ +[A-Za-z_0-9]+$/, "", p[i])  # drop the parameter name
        out = out (out == "" ? "" : ",") p[i]
    }
    return name "|" out
}
FNR == 1 { CLASS = FILENAME; sub(/\.java$/, "", CLASS); SUB = 0 }
FILENAME != "Item.java" && /^public (abstract )?class [A-Za-z]+ extends [A-Za-z]+/ {
    match($0, /class [A-Za-z]+ extends [A-Za-z]+/)
    split(substr($0, RSTART, RLENGTH), w, " ")
    print "extends " w[2] " " w[4]
    SUB = 1
}
{
    s = sig($0)
    if (s == "") next
    split(s, a, "|")
    if (FILENAME == "Item.java") {
        if (MODS ~ / static / || MODS ~ / final / || MODS ~ / private /) next
        base[s] = 1
        print "method " a[1] " " FNR (a[2] == "" ? "" : " " a[2])
    } else if (SUB && (s in base) && MODS !~ / static /) {
        print "override " CLASS " " a[1] " " FNR
    }
}
' Item.java $(ls Item?*.java) | sort)

{
    echo "# Item.java override set of the vanilla b1.7.3 client (PLAN_v4 D2), generated by"
    echo "# crates/mc-sim/tests/data/gen_item_overrides.sh from"
    echo "# .reference/mc_b1.7.3_release/1.7.3-LTS/src/minecraft/net/minecraft/src (Item.java and"
    echo "# every Item*.java subclass). Do not edit: rerun the script. Read by"
    echo "# crates/mc-sim/tests/item_dispatch_coverage.rs."
    echo "#"
    echo "# method <name> <Item.java line> <parameter types>    non-static, non-final, non-private Item methods"
    echo "# extends <Class> <Parent>                            every Item subclass"
    echo "# override <Class> <method> <Class.java line>         a subclass method with the signature of a method row"
    printf '%s\n' "$body"
} > "$OUT"
echo "gen_item_overrides: wrote $(grep -c '^override ' "$OUT") overrides, $(grep -c '^method ' "$OUT") methods, $(grep -c '^extends ' "$OUT") classes to $OUT"
