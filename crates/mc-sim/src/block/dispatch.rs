//! Block behaviour entry points (PLAN_v4 §3.2): `Block`'s overridable
//! methods as free functions that look the block up by id and `match` on its
//! [`BlockKind`].
//!
//! # Conventions every transcriber follows
//!
//! - Signature: Java's `(World world, int x, int y, int z, …)` becomes
//!   `(world: &mut World, id: i32, x, y, z, …)`. `id` replaces the `Block`
//!   receiver (`Block.blocksList[id]`); callers pass the id they looked up, as
//!   Java does before calling. Methods that only read the world take
//!   `&World`.
//! - Each function starts from the base `Block` implementation (the `_` arm,
//!   transcribed with its citation). An override gets its own arm, which calls
//!   a function in the module of the overriding class (`block/fire.rs`,
//!   `block/fluid.rs`, …) once transcribed.
//! - **Not yet transcribed** overrides are listed already, grouped by the
//!   class that defines the override (computed from the vanilla tree, so a
//!   subclass that inherits it, like `BlockGravel` from `BlockSand`, is in its
//!   parent's arm). Such an arm runs the base implementation and records
//!   `"Class.method"` with [`World::note_unimplemented`]. No `todo!()`: a
//!   fixture run shows exactly which overrides it reached. A transcriber
//!   replaces the arm; the list is the remaining work.
//! - `Random` parameters: every in-world caller passes `World.rand`
//!   (World.java:1159, :1960, :1988), so behaviour takes a
//!   [`RandomSource`] and draws through [`World::random`]. The two
//!   population callers (WorldGenLiquids.java:57, WorldGenHellLava.java:63)
//!   pass the generator's `Random`: [`RandomSource::ChunkProviderRand`]
//!   (WP-1.7), which the population features and the tree generators draw
//!   through as well.
//! - Signatures beyond the base rule: a Java `IBlockAccess` parameter is the
//!   `World` (the only `IBlockAccess` the simulation has; the client's
//!   `ChunkCache` reads the same data). Methods Java declares without a world
//!   (`getExplosionResistance`, `getRenderColor`, `canProvidePower`) take
//!   `&World` first so an untranscribed arm can record itself. A player
//!   parameter is `&mut Entity` where an override may change the player
//!   (`blockActivated`, `onBlockClicked`, `harvestBlock`), `&Entity` where all
//!   only read it (`onBlockPlacedBy`, `blockStrength`); an entity that Java
//!   allows to be null is `Option<&Entity>` (`getExplosionResistance`).
//! - An id with no block (Java: a `NullPointerException` at the caller,
//!   which vanilla never reaches) is not an error: the function records
//!   nothing and returns false, 0, `None` or the base value.
//!
//! # Coverage
//!
//! Every non-static, non-final, non-private method of `Block.java` that a
//! `Block*.java` class overrides has an entry point here, or is a data method
//! of [`crate::block`] ([`DATA_METHODS`]). `tests/block_dispatch_coverage.rs`
//! checks this against the override set of the vanilla tree
//! (`tests/data/block_overrides.txt`, generated by
//! `tests/data/gen_block_overrides.sh`): for every block id and every entry
//! point, the arm the id reaches must record exactly `"Class.method"` of the
//! class that defines the override it inherits, unless that pair is listed in
//! [`TRANSCRIBED`], in which case it must record nothing; ids that inherit
//! `Block`'s body must record nothing. **A task that transcribes an override
//! replaces its arm and adds the method to its class's row of
//! [`TRANSCRIBED`]**; the test then fails if the arm still records, or if any
//! override is neither recorded nor listed.
//!
//! Fully transcribed here already: `isOpaqueCube`, `renderAsNormalBlock`,
//! `tickRate` and the other [`DATA_METHODS`] (constants and field reads, in
//! [`crate::block`]), the base `Block` implementations of everything below,
//! and the overrides listed in [`TRANSCRIBED`] (`BlockSand`, inherited by
//! `BlockGravel`, in [`super::sand`]; `BlockFluid`, `BlockFlowing` and
//! `BlockStationary` in [`super::fluid`]; the `BlockFluid.canCollideCheck`
//! and `BlockStairs` one-liners here; the redstone classes
//! `BlockRedstoneWire`, `BlockTorch`, `BlockRedstoneTorch`,
//! `BlockRedstoneRepeater`, `BlockButton`, `BlockLever`,
//! `BlockPressurePlate`, `BlockRedstoneOre` in the modules of the same
//! names; `BlockRail`, with `RailLogic`, in [`super::rail`] and
//! `BlockDetectorRail` in [`super::detector_rail`]; the container blocks
//! of WP-1.8 in [`super::container`], [`super::chest`], [`super::furnace`],
//! [`super::dispenser`], [`super::note`], [`super::sign`],
//! [`super::jukebox`]).

