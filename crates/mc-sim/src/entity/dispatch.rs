//! Virtual dispatch for `Entity` methods (module docs of [`crate::entity`]).
//!
//! One function per overridable method that transcribed code calls. Each
//! `match` lists every concrete kind under the class whose body it runs
//! (computed from the vanilla tree, inheritance resolved). Arms for overrides
//! that are not transcribed yet run the nearest transcribed ancestor's body and
//! record `"Class.method"` in [`World::unimplemented_hits`].
//!
//! # Coverage
//!
//! Every non-static, non-final, non-private method of `Entity.java` that an
//! in-scope subclass overrides has an entry point here, or is listed in
//! [`NOT_DISPATCHED`] with the reason. `tests/entity_dispatch_coverage.rs`
//! checks this against the override set of the vanilla tree
//! (`tests/data/entity_overrides.txt`, generated by
//! `tests/data/gen_entity_overrides.sh`): for every kind and every entry
//! point, the call must record `"Class.method"` of the class that defines the
//! override the kind inherits, unless that pair is in [`TRANSCRIBED`], in
//! which case it must record nothing of its own; it may also record the
//! partial bodies of that class's ancestors it runs (`EntityLiving.onUpdate`
//! records the part of itself it does not transcribe yet). Kinds that inherit
//! `Entity`'s body record nothing. **A task that transcribes an override
//! replaces its arm and adds the method to its class's row of
//! [`TRANSCRIBED`]** (block dispatch convention, `crate::block::dispatch`).

